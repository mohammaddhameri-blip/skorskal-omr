// SMADBOD Attendance Bridge: sealed transmission, no idMe credentials.
export const BRIDGE_URL='https://qekcgsfeomjckctiubgm.supabase.co/functions/v1/smadbod-attendance-bridge';
export function parsePairing(value){
  const text=String(value||'').trim();
  const m=/^SB1\.([A-Za-z0-9_-]{43})\.([A-Za-z0-9_-]{43})$/.exec(text);
  if(!m)throw new Error('Enter the pairing code generated by the work-PC extension.');
  return {token:m[1],key:m[2]};
}
function bytes(s){
  const b64=s.replace(/-/g,'+').replace(/_/g,'/')+'='.repeat((4-s.length%4)%4);
  return Uint8Array.from(atob(b64),c=>c.charCodeAt(0));
}
function base64url(array){
  let b='';for(const x of array)b+=String.fromCharCode(x);
  return btoa(b).replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');
}
export async function submitAttendance(pairText,payload){
  const p=parsePairing(pairText);
  if(!globalThis.crypto?.subtle)throw new Error('Secure HTTPS browser required.');
  if(!payload||payload.schema!=='smadbod.attendance.v1')throw new Error('Unsupported attendance record');
  const iv=crypto.getRandomValues(new Uint8Array(12));
  const key=await crypto.subtle.importKey('raw',bytes(p.key),{name:'AES-GCM'},false,['encrypt']);
  const plaintext=new TextEncoder().encode(JSON.stringify(payload));
  const encrypted=await crypto.subtle.encrypt({name:'AES-GCM',iv},key,plaintext);
  const response=await fetch(BRIDGE_URL,{
    method:'POST',cache:'no-store',
    headers:{'Content-Type':'application/json','x-bridge-token':p.token},
    body:JSON.stringify({action:'push',client_ref:crypto.randomUUID(),iv:base64url(iv),ciphertext:base64url(new Uint8Array(encrypted))})
  });
  let result={};try{result=await response.json()}catch{}
  if(!response.ok||!result.ok)throw new Error(result.error||'Unable to send attendance.');
  return result;
}
